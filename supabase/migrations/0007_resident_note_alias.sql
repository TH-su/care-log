-- 0007: 申し送りでの表示名（同姓の入居者の取り違えを防ぐ）
--
-- 0001〜0006 を当てたあとに実行する。冪等（何度実行しても同じ結果）。
-- 既存のテーブル・列・データは一切削除しない（列の追加のみ）。
--
-- 背景（2026-09-01 指示）:
--   同じ姓の入居者が複数おられ、申し送り表で記載先を間違える・情報を取り違える
--   恐れがある。現行のスプレッドシートでは「【下の名前】姓」のように下の名前を
--   括弧で目立たせて書き分けていた。
--
--   利用者マスタの氏名（residents.name）は正本（ワイズマン側の名簿）から
--   GAS 経由で同期しているので、**直接書き換えてはいけない**。
--   ・次の同期で元に戻る
--   ・過去データ取込（tools/import.mjs）の名寄せが氏名で照合しているため壊れる
--   そこで「申し送りでだけ使う表示名」を別の列として持たせる。
--
-- この列の意味:
--   note_alias が空（null）… 従来どおり residents.name をそのまま表示する
--   note_alias に値がある … **申し送りを扱う画面でだけ**その文字を表示する
--                            （バイタル・食事・カルテ・外出外泊はマスタの氏名のまま）
--
-- マスタ同期との関係:
--   src/lib/gasClient.ts の applyResidents は
--   name / kana / room / gender / care_level / active / needs_review しか書かない。
--   したがってこの列は同期で上書きされない（staff.manual のような
--   退職判定の除外は不要＝表示だけの列なので同期の判断に一切関与しない）。
--
-- ★ do $$ … $$ のブロックは使わない（Supabase の SQL エディタが誤解釈するため。
--   2026-08-28 に実機で確認済み）。
-- =====================================================================

alter table residents add column if not exists note_alias text;

comment on column residents.note_alias is
  '申し送りでの表示名。同姓の入居者を見分けるための表示専用の別名で、申し送りを扱う画面だけに出す。空なら name を表示する。マスタ同期はこの列に触れない。';

-- PostgREST のスキーマキャッシュを即時リロード（適用直後の 404/PGRST205 期間を短縮）
notify pgrst, 'reload schema';

