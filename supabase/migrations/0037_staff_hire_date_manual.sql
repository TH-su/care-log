-- 0037: 職員の入職日を事務所が手で決めた印（staff.hire_date_manual）（本人指示 2026-10-19）
--
-- 0001〜0036 を当てたあとに実行する。冪等（何度実行しても同じ結果）。
-- 列を1つ足すだけ（既定は false。既存の行・データには触れない）。
--
-- なぜ: 入職日は名簿の同期で職員マスタから氏名で結んで書く（0036）。名簿に姓だけで載る職員で、職員マスタに
--   同じ姓の在籍の方が2人以上いる時などは、プログラムでは誰か決められず並びが正しくならない。設定画面で
--   事務・管理者が入職日を手で入れられるようにし、手で入れた入職日は同期で上書きしない（この列が true の行）。
--
-- 旧クライアント×新サーバー: 旧版はこの列を読まない。旧版の同期は手で入れた入職日を職員マスタの日付で
--   上書きしうる（結べた職員だけ）＝全端末が新しい版になってから手で入れるのが確実。データは消えない。
-- 新クライアント×旧サーバー: 新版は職員を読む時にこの列を選ぶので、列が無いと職員の読み取りが失敗する
--   ＝**この移行を当ててからアプリを公開する**。
--
-- ★ do $$ … $$ のブロックは使わない（Supabase の SQL エディタが誤解釈するため）。
-- 個人情報: このファイルに実在の氏名を書かない（構造だけを定義する）。
-- =====================================================================

alter table public.staff add column if not exists hire_date_manual boolean not null default false;

comment on column public.staff.hire_date_manual is
  '入職日を設定画面で手で入れた（true）。名簿の同期はこの行の入職日を上書きしない。2026-10-19';

notify pgrst, 'reload schema';

