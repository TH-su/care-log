-- =====================================================================
-- 0009: 施設長として選べる職員を固定する
--
-- 0001〜0008 を当てたあとに実行する。冪等（何度実行しても同じ結果）。
-- 既存のテーブル・列・データは一切削除しない（設定値を1行入れるだけ）。
--
-- 背景（2026-09-05 指示）:
--   日報の「施設長」欄が職員名簿の全員から選べるため、誤って別の職員を
--   施設長として登録できてしまう。施設長は1名なので、その1名だけを選べるようにする。
--
-- ★ここに氏名は書かない。**職員IDだけ**を設定値として持つ。
--   理由: このリポジトリは公開されるため、実在の職員名をコード・移行ファイル・
--   コメントに残さない（公開前チェックリスト A-1）。
--
-- 値を変えるとき（施設長が交代した時）:
--   1. 新しい施設長の職員IDを調べる
--        select id from staff where active and name = '（氏名）';
--   2. 設定値を差し替える
--        update app_settings set value = '（そのID）' where key = 'manager_staff_id';
--   ※ 1・2 はターミナルで実行する。氏名をこのファイルに書き足さないこと。
--
-- 設定が無い場合・その職員が名簿から消えた場合、アプリは**従来どおり全員から選べる**
--   （固定に失敗して選べなくなる、という状態を作らない安全側の作り）。
--
-- ★ do $$ … $$ のブロックは使わない（Supabase の SQL エディタが誤解釈するため）。
-- =====================================================================

insert into app_settings (key, value)
values ('manager_staff_id', '1')
on conflict (key) do nothing;   -- 既に設定済みなら上書きしない（現場の変更を尊重する）

comment on table app_settings is
  'アプリ全体の設定値。native_input_enabled=アプリ入力の解禁／facility_name=施設名／manager_staff_id=施設長として選べる職員のID。';

notify pgrst, 'reload schema';

