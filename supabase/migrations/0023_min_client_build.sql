-- 設定の行を1つ足すだけ（値は空＝制限なし）。既に行があれば触らない（現場で入れた値を戻さない）。
--
-- 何に使うか:
--   互換の無い変更（古い版の書き方をサーバーで閉じる等）を配る時、古い版のまま開きっぱなしの端末の入力を止める。
--   値は「入力を許す最も古い公開の通し番号」（GitHub Actions の run_number＝設定画面の「アプリの版」の #番号）。
--   端末は入力解禁の確認（getNativeInputGate・getKindInputGate）と同じ経路でこの値を読み、自分の版の通し番号が
--   これより小さければ入力と送信待ちの送信を止め、記録の画面を「新しい版に更新してください〔更新〕」の受け皿に置き換える
--   （入力中の内容がある間は画面を残して帯で知らせる。ヘッダ・タブ・未送信の件数は残る。自動では再読み込みしない）。
--   空・数字でない値は「制限なし」。手元の開発の版（通し番号の無い 'dev'）は止めない。
--
-- 値を変える時（Supabase の SQL エディタで。0022 で端末からは書けない）:
--   update public.app_settings set value = '（入力を許す最も古い通し番号）' where key = 'min_client_build';
--   戻す（制限なしにする）: update public.app_settings set value = '' where key = 'min_client_build';
--   ★上げる前に、設定画面の「アプリの版」で全端末がその番号以上になったか、未送信が0件かを確かめる。
--     止まった端末の未送信は端末に残る（消えない）。〔更新〕で新しい版になれば、その版が送る。
--
-- 限界: この確認を持つ版（2026-10-10 以降の公開）からしか効かない。それより前の版の端末は値を読まないので止まらない。
--
-- 旧クライアント×新サーバー: 旧版は min_client_build を読まない（app_settings はキーを指定して読む）ので何も変わらない。
--   データは消えない。
-- 新クライアント×旧サーバー: 行が無い＝未登録は「制限なし」として扱う（入力は止めない）。
--
-- ★ do $$ … $$ のブロックは使わない（Supabase の SQL エディタが誤解釈するため）。
-- 個人情報: このファイルに実在の氏名を書かない。
