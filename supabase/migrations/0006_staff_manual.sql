-- 0006: 手で登録した職員（シフト名簿に載らない事務職員など）
--
-- 0001〜0005 を当てたあとに実行する。冪等（何度実行しても同じ結果）。
-- 既存のテーブル・列・データは一切削除しない（列の追加のみ）。
--
-- 背景（2026-08-29）:
--   職員名簿はシフト連携GASから同期しているが、そこに載るのは
--   シフトを組む職種だけ。事務職員は載らない。
--   一方で事務職員も申し送りを書いており、実データで2名・770件の記入者になっていた。
--   手で staff に追加しても、次のマスタ同期が「名簿に居ない在籍者」として
--   退職扱いにしてしまい、記録者として選べなくなる。
--
-- この列の意味:
--   manual = true … 人が登録した職員。**マスタ同期の退職判定から外す**。
--   manual = false … シフト名簿から同期した職員（従来どおり名簿が正）。
--
-- ★ do $$ … $$ のブロックは使わない（Supabase の SQL エディタが誤解釈するため。
--   2026-08-28 に実機で確認済み）。
-- =====================================================================

alter table staff add column if not exists manual boolean not null default false;

comment on column staff.manual is
  '人が手で登録した職員（シフト名簿に載らない事務職員など）。true の行はマスタ同期の退職判定から除外する。';

-- PostgREST のスキーマキャッシュを即時リロード（適用直後の 404/PGRST205 期間を短縮）
notify pgrst, 'reload schema';

