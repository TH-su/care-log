-- 0026: 日報の施設長は1日1人（サーバーで強制する部分一意索引）（監査 F70・2026-10-10 本人回答）
--
-- 0001〜0025 を当てたあとに実行する。冪等（何度実行しても同じ結果）。
-- テーブル・列・データには触れない（索引を1つ足すだけ）。
--
-- なぜ:
--   2台の端末が同じ日の日報を開いたまま、A が施設長に職員01、B が（古い画面のまま）職員04 を選ぶと、
--   attendance に施設長（role='manager'）が2行残った。日報は施設長を1人だけ出す（find）ので、2人目は施設長欄にも
--   出勤者欄にも出ず、日報から消えて見えた。施設長として選べる職員を固定する設定（0009 の manager_staff_id）が
--   外れている時（設定の職員が在籍していない・設定を読めなかった）に起きる。
--
-- 形:
--   ・表示中（sort >= 0）の施設長を日ごとに1行だけにする部分一意索引。外した行（sort < 0）は数えない
--     （外した施設長の行は残し、戻せるようにする）。
--   ・後から選んだ端末の保存は 23505（索引の名前 uq_attendance_manager_day）で止まる。新しい版の端末はこれを
--     「施設長は他の端末で選ばれています（最新に更新して選び直す）」として出し、送信待ちの再送は「止まっている
--     送信待ち」（設定タブ）に残す（黙って捨てない）。
--   ・施設長の入れ替え（前の施設長を外して別の人を選ぶ）は、新しい版の端末は「前の施設長を外す→新しい施設長を
--     入れる」の順で書く（索引に当たらない）。
--
-- ★適用の順番: **アプリの配信が先、この移行が後**（multi-device-sync「互換の無い変更はアプリ先」）。
--   旧版の端末は施設長の入れ替えで「新しい施設長を入れる→前の施設長を外す」の順に書くので、この索引の下では
--   入れ替えの保存が 23505 で止まる（「他の端末が同時に出勤者を保存したため、保存できませんでした」と出て画面は
--   元に戻る。サーバーの施設長は前のまま＝データは消えない）。施設長の固定（manager_staff_id）が効いている間は
--   入れ替えそのものが起きない。全端末が新しい版になったこと（設定画面の「アプリの版」・0023 の min_client_build）を
--   確かめてから流す。
--
-- ★適用の前に、施設長が2人いる日が無いことを確かめる（あると索引を作れずにこのファイルが失敗する＝何も変わらない）:
--    select day, array_agg(staff_id order by sort, staff_id) as managers
--      from public.attendance where role = 'manager' and sort >= 0
--     group by day having count(*) > 1 order by day;
--   → 0行なら流してよい。行が出たら、その日の日報で施設長を1人にしてから流す（自動では直さない＝どちらを残すかは人が決める）。
--
-- 旧クライアント×新サーバー: 上の「適用の順番」のとおり。止まった保存は端末の画面で元に戻り（オンライン）、
--   旧版の送信待ちは 'rejected' として外れることがある（その操作は施設長の2人目を作る操作）。サーバーの行は消えない。
-- 新クライアント×旧サーバー: 索引が無いので、新しい版の「外す→入れる」の順の書き込みもそのまま通る。
--
-- ★ do $$ … $$ のブロックは使わない（Supabase の SQL エディタが誤解釈するため）。
-- 個人情報: このファイルに実在の氏名を書かない（構造だけを定義する）。
-- =====================================================================

create unique index if not exists uq_attendance_manager_day
  on public.attendance (day)
  where role = 'manager' and sort >= 0;

comment on index public.uq_attendance_manager_day is
  '日報の施設長は1日1人（表示中＝sort >= 0 の role=manager）。外した行（sort < 0）は数えない。2026-10-10 F70。';

notify pgrst, 'reload schema';

