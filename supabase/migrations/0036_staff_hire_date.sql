-- 0036: 職員の入職日（staff.hire_date）を持つ（職員を選ぶ欄を入職日の順に並べる・本人指示 2026-10-19）
--
-- 0001〜0035 を当てたあとに実行する。冪等（何度実行しても同じ結果）。
-- 列を1つ足すだけ（値は空で足す。既存の行・データには触れない）。
--
-- なぜ: 0035 の hire_order（シフト作成アプリの職員の一覧の order）は、画面で並べた順・登録した順の番号で、
--   本当の入職日の順ではなかった（本人確認 2026-10-19「入職順になっていない」）。入職日の正本は職員マスタ
--   （入職日は必須の欄）なので、名簿の同期の時に職員マスタの入職日を読んで、氏名で結べた職員に書く。
--   同じ氏名の職員が職員マスタに2人以上いる時は書かない（取り違えを避ける）。職員マスタに居ない職員は空のまま。
--
-- 旧クライアント×新サーバー: 旧版はこの列を読まない・書かないので、今までどおりの順で並ぶだけ（データは消えない）。
-- 新クライアント×旧サーバー: 新版は職員を読む時にこの列を選ぶので、列が無いと職員の読み取りが失敗する
--   ＝**この移行を当ててからアプリを公開する**。
--
-- ★ do $$ … $$ のブロックは使わない（Supabase の SQL エディタが誤解釈するため）。
-- 個人情報: このファイルに実在の氏名を書かない（構造だけを定義する）。
-- =====================================================================

alter table public.staff add column if not exists hire_date date;

comment on column public.staff.hire_date is
  '入職日（職員マスタの入職日）。名簿の同期が氏名で結べた職員に書く。空は職員マスタで結べない職員（選ぶ欄では末尾）。2026-10-19';

notify pgrst, 'reload schema';

